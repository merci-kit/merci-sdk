// @ts-check

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { CAPABILITY, CAPABILITY_REGISTRY, WEB_SEARCH_MODES, WEB_SCRAPE_MODES, BROWSER_MODES } from '../lib/core/constants/index.mjs';
import { NATIVE_PROVIDERS as WEB_SEARCH_NATIVE } from '../lib/agentic/websearch/engines.mjs';
import { NATIVE_PROVIDERS as WEB_SCRAPE_NATIVE } from '../lib/agentic/webscrape/engines.mjs';

const BACKENDS_BY_CAPABILITY = {
    [CAPABILITY.WEB_SEARCH]: { native: WEB_SEARCH_NATIVE, modes: WEB_SEARCH_MODES },
    [CAPABILITY.WEB_SCRAPE]: { native: WEB_SCRAPE_NATIVE, modes: WEB_SCRAPE_MODES },
    // ponytail: the browser has no server-side native leg by design — the
    [CAPABILITY.BROWSER]: { native: null, modes: BROWSER_MODES },
};


/**
 * Builds the capability matrix rows from the live code sets.
 * @returns {Array<{id: string, loadTool: string, saveTool: string, nativeProviders: string, modes: string}>}
 */
export function buildMatrix() {
    return Object.values(CAPABILITY).map((id) => {
        const registry = CAPABILITY_REGISTRY[id] ?? {};
        const backends = BACKENDS_BY_CAPABILITY[id];
        return {
            id,
            loadTool: registry.loadTool ?? '—',
            saveTool: registry.saveTool ?? '—',
            nativeProviders: !backends
                ? '(backend-agnostic)'
                : (backends.native && backends.native.size
                    ? [...backends.native].sort().join(', ')
                    : '(none)'),
            modes: backends ? backends.modes.join(', ') : '—',
        };
    });
}


/**
 * Renders the matrix as a standalone HTML page.
 * @returns {string}
 */
export function renderMatrix() {
    const rows = buildMatrix()
        .map((r) => `      <tr><td>${r.id}</td><td>${r.loadTool}</td><td>${r.saveTool}</td><td>${r.nativeProviders}</td><td>${r.modes}</td></tr>`)
        .join('\n');
    return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>Merci SDK — Capability Matrix</title>
</head>
<body>
  <h1>Capability Matrix</h1>
  <p>Generated by <code>scripts/build-matrix.mjs</code> — do not edit by hand. Run <code>pnpm run build:matrix</code> to regenerate.</p>
  <table border="1" cellpadding="6" cellspacing="0">
    <thead>
      <tr><th>Capability</th><th>Load tool</th><th>Save tool</th><th>Native providers</th><th>Modes</th></tr>
    </thead>
    <tbody>
${rows}
    </tbody>
  </table>
</body>
</html>
`;
}

/**
 * `argv[1]` may be a symlinked or vanished path; compare real paths without throwing.
 * @type {(p: string) => string}
 */
const canonical = (p) => { try { return fs.realpathSync(path.resolve(p)); } catch { return path.resolve(p); } };

if (process.argv[1] && canonical(process.argv[1]) === canonical(fileURLToPath(import.meta.url))) {
    const out = path.resolve('docs/capability_matrix.html');
    fs.writeFileSync(out, renderMatrix(), 'utf8');
    console.log(`Generated: ${out}`);
}
